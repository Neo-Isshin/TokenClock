const assert = require('node:assert/strict');
const { ip, isPublic, candidate, rtcVerdict, dnsVerdict } = require('./probe.js');
assert.equal(ip('1.2.3.999'), null);
assert.equal(ip('bad.local'), null);
assert.equal(ip('2001:4860:4860:0:0:0:0:8888'), '2001:4860:4860::8888');
for (const value of ['10.0.0.1', '127.0.0.1', '192.168.1.1', '100.64.1.2', '198.18.1.2', '169.254.0.1', '::1', 'fc00::1', 'fe80::1', '2001:db8::1', '::ffff:192.168.1.1']) assert.equal(isPublic(value), false, value);
for (const value of ['1.1.1.1', '8.8.8.8', '2001:4860:4860::8888']) assert.equal(isPublic(value), true);
assert.deepEqual(candidate({ candidate: 'candidate:1 1 udp 123 1.1.1.1 777 typ srflx' }), { kind: 'public', address: '1.1.1.1' });
assert.equal(candidate({ address: 'a.local' }).kind, 'mdns');
assert.equal(candidate({ address: '8.8.8.8', type: 'relay' }).kind, 'relay');
assert.equal(rtcVerdict('1.1.1.1', [], true), 'incomplete');
assert.equal(rtcVerdict('1.1.1.1', [{ kind: 'local', address: '192.168.1.1' }], true), 'incomplete');
assert.equal(rtcVerdict('1.1.1.1', [{ kind: 'public', address: '8.8.8.8' }], true), 'risk');
assert.equal(rtcVerdict('1.1.1.1', [{ kind: 'public', address: '1.1.1.1' }], true), 'match');
assert.equal(rtcVerdict('1.1.1.1', [{ kind: 'public', address: '1.1.1.1' }], false), 'review');
assert.equal(rtcVerdict('1.1.1.1', [{ kind: 'public', address: '2001:4860::1' }], true), 'review');
assert.equal(dnsVerdict([], '1.1.1.1'), 'incomplete');
assert.equal(dnsVerdict(['1.1.1.1'], ''), 'review');
assert.equal(dnsVerdict(['1.1.1.1'], '1.1.1.1，8.8.8.8'), 'match');
assert.equal(dnsVerdict(['9.9.9.9'], '1.1.1.1'), 'risk');
assert.equal(dnsVerdict(['1.1.1.1'], 'not-an-ip'), 'invalid');
console.log('Network classification checks passed');
const { exitsVerdict, locationVerdict, ipv6Verdict, aiVerdict } = require('./diagnostics.js');
const exit = { id:'ipify', category:'exit', state:'observed', ip:'1.1.1.1', country:'AU' };
assert.equal(exitsVerdict('1.1.1.1', []), 'incomplete');
assert.equal(exitsVerdict('1.1.1.1', [exit]), 'match');
assert.equal(exitsVerdict('8.8.8.8', [exit]), 'review');
assert.equal(exitsVerdict('1.1.1.1', [{...exit,id:'ailyre'}]), 'incomplete');
assert.equal(locationVerdict('1.1.1.1', [exit,{...exit,id:'ailyre'}]), 'incomplete');
const geo = {id:'ipwho',label:'IPWhois',category:'geo',state:'observed',ip:'1.1.1.1',country:'AU'};
assert.equal(locationVerdict('1.1.1.1', [exit,geo]), 'match');
assert.equal(locationVerdict('1.1.1.1', [exit,{...geo,country:'US'}]), 'review');
assert.equal(locationVerdict('8.8.8.8', [exit,geo]), 'incomplete');
const v6 = {id:'ipv6',category:'ipv6',state:'observed',ip:'2001:4860::1'};
assert.equal(ipv6Verdict([],[],false), 'notObserved');
assert.equal(ipv6Verdict([v6],[],false), 'review');
assert.equal(ipv6Verdict([v6],[],true), 'risk');
assert.equal(ipv6Verdict([v6],[{kind:'public',address:v6.ip}],false), 'match');
assert.equal(ipv6Verdict([v6],[{kind:'public',address:'2001:4860::2'}],false), 'risk');
assert.equal(aiVerdict('1.1.1.1',{state:'responded',httpStatus:200}), 'incomplete');
assert.equal(aiVerdict('1.1.1.1',{state:'responded',httpStatus:403}), 'incomplete');
assert.equal(aiVerdict('1.1.1.1',{state:'observed',ip:'1.1.1.1'}), 'match');
assert.equal(aiVerdict('1.1.1.1',{state:'observed',ip:'8.8.8.8'}), 'review');
console.log('Exit, country, IPv6 and AI route checks passed');

const {dohVerdict,overall}=require('./diagnostics.js');
assert.equal(dohVerdict('1.1.1.1',[{category:'doh',state:'verified'}]),'incomplete');
assert.equal(dohVerdict('1.1.1.1',[{category:'dohEcho',state:'observed',ip:'8.8.8.8'}]),'review');
assert.equal(dohVerdict('1.1.1.1',[{id:'ailyre',proxy:true},{category:'doh',state:'verified',proxy:false}]),'review');
assert.equal(dohVerdict('1.1.1.1',[{id:'ailyre',proxy:false},{category:'doh',state:'verified',proxy:false}]),'incomplete');
assert.deepEqual(overall({dns:'risk',doh:'review',ipv6:'notObserved',rtc:'match'}),{risk:['dns'],review:['doh'],unknown:['ipv6']});
const html=require('fs').readFileSync(__dirname+'/index.html','utf8');
for(const id of ['dohTitle','dohBadge','dohAddresses','overallSummary'])assert(html.includes('id="'+id+'"'),id);
console.log('DoH and summary checks passed');
